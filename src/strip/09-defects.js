      + ni(0) + uc(0) + sn(0) + P(`M${q(X(-HB))},${q(Y(4.4))} Q${q(X(-9.6))},${q(Y(2))} ${q(X(-11.2))},${q(Y(-0.2))}`, 'st09-hot') + P(`M${q(X(HB))},${q(Y(4.4))} Q${q(X(9.6))},${q(Y(2))} ${q(X(11.2))},${q(Y(-0.2))}`, 'st09-hot')
